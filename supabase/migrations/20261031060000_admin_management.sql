-- Admin management for Mon Électricité.
-- Admins may manage subscriptions and unpaid invoices; they cannot create
-- payments/receipts or mark an invoice as paid. Payments remain provider-only.

begin;

-- Mirror Auth email into the protected profile row so the admin UI can list
-- customers without exposing the auth schema through the client API.
alter table public.profiles add column if not exists email text;
create index if not exists profiles_email_idx on public.profiles (email);
update public.profiles p
set email = u.email
from auth.users u
where p.id = u.id and p.email is distinct from u.email;

create or replace function app_private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, phone, email)
  values (
    new.id,
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'display_name'), ''), ''),
    nullif(new.phone, ''),
    new.email
  )
  on conflict (id) do update
    set phone = excluded.phone,
        email = excluded.email,
        updated_at = now();
  return new;
end;
$$;

revoke all on function app_private.handle_new_auth_user() from public, anon, authenticated;
drop trigger if exists on_auth_user_updated_profile on auth.users;
create trigger on_auth_user_updated_profile
after update of email, phone, raw_user_meta_data on auth.users
for each row execute function app_private.handle_new_auth_user();

-- Append-only audit trail. No client role can insert, update, or delete logs.
create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles (id) on delete set null,
  action text not null check (char_length(action) between 1 and 40),
  entity_type text not null check (char_length(entity_type) between 1 and 40),
  entity_id uuid,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);
create index if not exists admin_audit_log_created_idx
  on public.admin_audit_log (created_at desc);
create index if not exists admin_audit_log_actor_idx
  on public.admin_audit_log (actor_id, created_at desc);

alter table public.admin_audit_log enable row level security;
revoke all privileges on table public.admin_audit_log from public, anon, authenticated;
grant select on table public.admin_audit_log to authenticated;
drop policy if exists admin_audit_log_read_admin on public.admin_audit_log;
create policy admin_audit_log_read_admin
  on public.admin_audit_log for select to authenticated
  using ((select app_private.is_admin()));

create or replace function app_private.audit_admin_mutation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_entity_id uuid;
begin
  if not (select app_private.is_admin()) then
    raise exception 'Admin role required';
  end if;

  if tg_op = 'INSERT' then
    v_new := to_jsonb(new);
    if tg_table_name = 'subscriptions' then
      v_new := v_new - 'service_address' - 'meter_number';
    end if;
    v_entity_id := (to_jsonb(new) ->> 'id')::uuid;
  else
    v_old := to_jsonb(old);
    v_new := to_jsonb(new);
    if tg_table_name = 'subscriptions' then
      v_old := v_old - 'service_address' - 'meter_number';
      v_new := v_new - 'service_address' - 'meter_number';
    end if;
    v_entity_id := (to_jsonb(new) ->> 'id')::uuid;
  end if;

  insert into public.admin_audit_log (
    actor_id, action, entity_type, entity_id, old_data, new_data
  ) values (
    auth.uid(), lower(tg_op), tg_table_name, v_entity_id, v_old, v_new
  );
  return new;
end;
$$;
revoke all on function app_private.audit_admin_mutation() from public, anon, authenticated;

grant insert, update on table public.subscriptions to authenticated;
grant insert, update on table public.invoices to authenticated;

drop policy if exists subscriptions_admin_insert on public.subscriptions;
create policy subscriptions_admin_insert
  on public.subscriptions for insert to authenticated
  with check ((select app_private.is_admin()));
drop policy if exists subscriptions_admin_update on public.subscriptions;
create policy subscriptions_admin_update
  on public.subscriptions for update to authenticated
  using ((select app_private.is_admin()))
  with check ((select app_private.is_admin()));

drop policy if exists invoices_admin_insert_unpaid on public.invoices;
create policy invoices_admin_insert_unpaid
  on public.invoices for insert to authenticated
  with check (
    (select app_private.is_admin())
    and status in ('due', 'overdue', 'cancelled')
  );
drop policy if exists invoices_admin_update_unpaid on public.invoices;
create policy invoices_admin_update_unpaid
  on public.invoices for update to authenticated
  using ((select app_private.is_admin()) and status <> 'paid')
  with check (
    (select app_private.is_admin())
    and status in ('due', 'overdue', 'cancelled')
  );

-- No DELETE policy or grant is added. Paid invoices can only be changed by a
-- future verified payment backend, never by the admin/mobile client.
drop trigger if exists subscriptions_admin_audit on public.subscriptions;
create trigger subscriptions_admin_audit
after insert or update on public.subscriptions
for each row execute function app_private.audit_admin_mutation();
drop trigger if exists invoices_admin_audit on public.invoices;
create trigger invoices_admin_audit
after insert or update on public.invoices
for each row execute function app_private.audit_admin_mutation();

commit;
